/* ---------------------------- ИИ №51: заходить в зазор стены рядом, иначе ломать её, а не обходить ---------------------------- */
// Прямой запрос пользователя: "ии игнорирует стены вообще, а надо чтобы
// если в близи зазор то заходил, а если нет [зазора], или он слишком
// далеко, то сам ломал, а то он пытается обойти когда как его ломают
// танки и турели". Симметрично для ОБЕИХ сторон — и вражеского ИИ (штурмует
// базу игрока), и юнитов игрока (штурмуют базу ИИ), т.к. вся эта механика
// завязана на общий setUnitDestination (03-pathfinding.js), который
// используют оба.
//
// ДИАГНОЗ (по факту чтения 03-pathfinding.js/06-enemy-ai.js/09-input.js):
// findPath (A*) считает ЛЮБУЮ чужую стену честным непроходимым
// препятствием (buildOccupancyGrid) — маршрут всегда строится В ОБХОД,
// вплоть до противоположной стороны периметра, если там окажется брешь.
// Никакого промежуточного решения "стена совсем рядом почти по пути, но
// без зазора — проще пробить её" в коде не существовало вовсе: юнит либо
// идёт мимо целого сегмента стены как ни в чём не бывало (если A* нашёл
// зазор где-то на маршруте), либо кружит вокруг всего периметра.
//
// РЕШЕНИЕ: патчим setUnitDestination (единственная точка входа для
// движения — используется и игроком, и вражеским ИИ без исключений, см.
// её же комментарий в 03-pathfinding.js) ДО вызова оригинала:
//  1) Проверяем, пересекает ли ПРЯМАЯ линия юнит->цель хотя бы одну чужую
//     стену (только чужую — свои стены и так прозрачны для патфайндинга,
//     см. buildOccupancyGrid(unitOwnerId), трогать нечего).
//  2) Если пересекает — ищем ближайший к этой линии ПРОХОДИМЫЙ зазор в
//     стене (клетку сетки патфайндинга рядом с линией пересечения, которая
//     НЕ занята стеной) в пределах GAP_SEARCH_RADIUS. Если такой зазор
//     нашёлся — ничего не меняем, отдаём управление оригинальному
//     setUnitDestination: A* и так проложит путь через него (он проходим
//     по построению), это и есть "если рядом зазор — заходит".
//  3) Если зазора рядом нет (все стены в радиусе поиска — сплошная стена
//     без разрывов, либо ближайший разрыв дальше GAP_SEARCH_RADIUS) —
//     юниту вместо движения к исходной цели ставится АТАКУЮЩАЯ цель:
//     ближайший к линии пересечения сегмент стены (attackTargetId), тем же
//     путём, что и явный клик игрока по зданию (см. 09-input.js) — юнит
//     подходит и разрушает именно этот кусок стены. Это и есть "сам ломал"
//     — той же механикой, которой уже пользуются танки/турели, когда игрок
//     или ИИ явно приказывает атаковать стену, просто триггер теперь
//     автоматический (упёрся в сплошную стену — начал её ломать), а не
//     только по явному клику.
//  4) После того как атакуемый сегмент стены разрушен (killBuilding,
//     07-game-loop-combat.js уже это делает сам), у юнита attackTargetId
//     обнуляется оригинальным боевым кодом — юнит "освобождается" и на
//     СЛЕДУЮЩИЙ вызов setUnitDestination (или на следующий decision-тик
//     ИИ/на следующий тик автопоиска updateCombat, если что-то другое
//     повторно позовёт его к той же исходной цели) снова пройдёт через
//     этот патч и, скорее всего, теперь пойдёт напрямую (пролом уже
//     открыт). Мы не переустанавливаем движение сами после слома —
//     полагаемся на то, что вызывающий код (enemyAttackStep,
//     enemyDefendBaseStep, 09-input.js и т.д.) и так периодически
//     переприказывает юнитам, следующим к своей цели (тот же паттерн,
//     что уже используют все существующие вызовы).
//
// Радиус "рядом" для поиска зазора (GAP_SEARCH_RADIUS) сознательно
// небольшой — несколько клеток сетки патфайндинга в обе стороны от точки
// пересечения линии со стеной. Если зазор объективно далеко (пришлось бы
// обходить половину периметра, чтобы его найти) — пользователь явно просил
// в этом случае ломать, а не тратить время на обход.
//
// Что этот патч НЕ трогает:
//  - Свои стены (unitOwnerId === b.ownerId) — они и так проходимы для
//    патфайндинга (ИИ №39), сквозь них юнит и так идёт напрямую.
//  - Призрачные (constructionMsLeft>0) стены — они физически не существуют
//    ни для occupancy (ИИ №46), ни для атаки (findAttackableAt) — этот
//    патч их тоже игнорирует, тем же условием.
//  - Летающих юнитов (def.flying) — они и так не пользуются A*/occupancy
//    вовсе (см. setUnitDestination), для них стены никогда не были
//    препятствием, патч их не касается.
//  - Явные приказы игрока атаковать конкретную цель (клик по юниту/зданию,
//    09-input.js) — этот патч работает только на уровне "куда физически
//    идти", он не переопределяет уже выставленный attackTargetId на
//    что-то ДРУГОЕ, кроме случая, когда обнаруживает сплошную стену на
//    пути к точке, куда движется юнит.
//
// Подключать ПОСЛЕДНИМ в index.html, после js/28-units-engage-enemies-enroute.js.

const WALL_BREACH_GAP_SEARCH_RADIUS = 2.5; // в клетках PATH_GRID_SIZE, в обе стороны от точки пересечения линии со стеной

(function patchSetUnitDestinationForWallBreaching() {
  if (typeof setUnitDestination !== "function") return;
  if (typeof buildOccupancyGrid !== "function") return;
  if (typeof worldToPathCell !== "function" || typeof pathCellKey !== "function") return;

  const _setUnitDestinationOriginal = setUnitDestination;

  // Находит первую чужую стену, которую пересекает отрезок (x0,y0)-(x1,y1),
  // семплированием точек вдоль отрезка с шагом ~половина клетки сетки
  // патфайндинга — карта прототипа небольшая, это дёшево и достаточно
  // точно для узкой (1 клетка) стены.
  function findWallCrossing(unitOwnerId, x0, y0, x1, y1) {
    const totalDist = Math.hypot(x1 - x0, y1 - y0);
    if (totalDist < 1) return null;
    const stepPx = PATH_GRID_SIZE / 2;
    const steps = Math.max(1, Math.ceil(totalDist / stepPx));
    for (let i = 0; i <= steps; i++) {
      const t = i / steps;
      const x = x0 + (x1 - x0) * t;
      const y = y0 + (y1 - y0) * t;
      // Ищем здание-стену конкретно в этой клетке — самый простой и
      // надёжный способ (без повторного обхода occupancy.cellOwner) это
      // прямой перебор построек рядом с точкой; карта небольшая, стены
      // узкие (1 клетка), лишних совпадений не бывает.
      const wallHere = Object.values(State.buildings).find(b =>
        b.type === "wall" && b.hp > 0 && !(b.constructionMsLeft > 0) &&
        b.ownerId !== unitOwnerId &&
        Math.abs(b.x - x) < PATH_GRID_SIZE / 2 && Math.abs(b.y - y) < PATH_GRID_SIZE / 2
      );
      if (wallHere) return { wall: wallHere, x, y };
    }
    return null;
  }

  // Есть ли проходимый (не занятый чужой стеной) зазор в клетках сетки
  // патфайндинга в радиусе GAP_SEARCH_RADIUS от точки пересечения —
  // ищем по расширяющимся квадратным кольцам клеток вокруг crossPoint.
  function hasNearbyGap(unitOwnerId, crossX, crossY) {
    const occupied = buildOccupancyGrid(unitOwnerId);
    const center = worldToPathCell(crossX, crossY);
    const r = Math.ceil(WALL_BREACH_GAP_SEARCH_RADIUS);
    for (let dc = -r; dc <= r; dc++) {
      for (let dr = -r; dr <= r; dr++) {
        if (Math.hypot(dc, dr) > WALL_BREACH_GAP_SEARCH_RADIUS) continue;
        const col = center.col + dc, row = center.row + dr;
        const key = pathCellKey(col, row);
        if (!occupied.has(key)) return true; // нашли проходимую клетку рядом — зазор есть
      }
    }
    return false;
  }

  setUnitDestination = function (u, goalX, goalY) {
    const def = UnitDefs[u.type];
    // Летающие юниты стены не касаются вовсе — не наш случай, оригинал
    // сам всё сделает как раньше (прямая линия, без A*).
    if (def && def.flying) { _setUnitDestinationOriginal(u, goalX, goalY); return; }
    // Юнит без урона (например, будущий не боевой тип) не может ломать
    // стену — не выставляем ему атакующую цель, просто пусть A* обходит
    // как раньше (оригинал).
    if (!def || !def.canAttack) { _setUnitDestinationOriginal(u, goalX, goalY); return; }

    const crossing = findWallCrossing(u.ownerId, u.x, u.y, goalX, goalY);
    if (!crossing) { _setUnitDestinationOriginal(u, goalX, goalY); return; } // прямая линия свободна — обычный путь

    const gapNearby = hasNearbyGap(u.ownerId, crossing.x, crossing.y);
    if (gapNearby) { _setUnitDestinationOriginal(u, goalX, goalY); return; } // зазор рядом есть — A* сам через него пройдёт

    // Зазора рядом нет (или он слишком далеко) — ломаем именно ЭТОТ
    // сегмент стены вместо похода в обход. Ставим его явной атакующей
    // целью — тем же путём, что и явный клик игрока по зданию
    // (09-input.js): u.attackTargetId + u.state="moving", движение к
    // самой стене (не к исходной goalX/goalY) через оригинальный
    // setUnitDestination, чтобы юнит физически подошёл на дистанцию атаки.
    u.attackTargetId = crossing.wall.id;
    u.attackMoveMode = false;
    _setUnitDestinationOriginal(u, crossing.wall.x, crossing.wall.y);
    u.state = "moving";
  };
})();
