/* ---------------------------- ИИ №50: юниты игрока не игнорируют вражеских юнитов при явном приказе атаки на здание ---------------------------- */
// Прямой запрос пользователя (2 связанные жалобы в одном репорте):
//  1) "мои юниты их юниты игнорируют вообще, когда как мои юниты их
//     грохают по порядку" — т.е. вражеский ИИ юнит атакует всё по пути
//     (турели/юниты/здания), а юнит ИГРОКА, получивший явный приказ
//     "атаковать здание/стену" (ПКМ по цели), идёт напролом к этому
//     зданию и в упор игнорирует вражеских юнитов рядом или на пути.
//  2) "юниты иногда зависают на месте, с анимацией ходьбы, но без
//     движения" — та же корневая причина: юнит идёт к зданию сквозь/мимо
//     вражеского юнита, applyUnitSeparation (07-game-loop-combat.js)
//     держит его физически на месте вплотную к чужому юниту, u.state
//     остаётся "moving" (анимация идёт), а u.x/u.y фактически не
//     продвигаются — визуально "стоит и топчется".
//
// ДИАГНОЗ (по факту чтения 07-game-loop-combat.js/09-input.js):
// Когда игрок кликает ПКМ по вражескому зданию/стене, 09-input.js ставит:
//   u.attackTargetId = clickedEnemy.id;
//   u.attackMoveMode = false;   // <-- корень проблемы
// В updateCombat (07-...js) автопоиск новой цели (findNearestEnemyInRange)
// вызывается ТОЛЬКО когда `!target` — а target тут НЕ null, это то самое
// явно выбранное здание, живое всё то время, что юнит идёт к нему. Условие
// автопоиска `u.state === "idle" || u.attackMoveMode` в этом случае вообще
// не имеет значения — до него код не доходит (см. `if (!target) return;`
// сразу после блока автопоиска). Юнит физически идёт к зданию, проходя
// мимо/через вражеских юнитов, ни разу не проверяя, не стоит ли атаковать
// кого-то из них в первую очередь. У вражеского ИИ такой проблемы нет —
// enemyAttackStep (06-enemy-ai.js) всегда ставит attackMoveMode=true, так
// что автопоиск у него живой с самого начала.
//
// РЕШЕНИЕ: не трогаем 09-input.js (явный клик по зданию должен по-прежнему
// давать явную цель — это ожидаемое поведение "разрушь именно это") и не
// трогаем updateCombat целиком (риск сломать существующий контракт
// приоритетов/leash). Вместо этого патчим updateCombat точечно: ПЕРЕД тем,
// как использовать уже найденный явный target, если этот target — ЗДАНИЕ
// (не юнит) и юнит НЕ в attackMoveMode (т.е. это ровно тот случай явного
// приказа "атакуй это здание"), дополнительно проверяем — нет ли сейчас
// вражеского ЮНИТА в радиусе автоагра. Если есть — временно переключаемся
// на него (не теряя исходную цель-здание: она остаётся сохранённой в
// отдельном поле u.buildingTargetId и юнит возвращается к ней, как только
// рядом никого не останется).
//
// Это даёт именно то поведение, о котором просил пользователь: "мои юниты
// грохают по порядку" — юнит бьёт всех вражеских юнитов, что попадаются на
// пути к зданию, а не идёт напролом мимо них, и заодно чинит "зависание с
// анимацией ходьбы" — юнит больше не пытается бесконечно проталкиваться
// сквозь стоящего на пути вражеского юнита, а останавливается и убивает
// его.
//
// Радиус обнаружения "по пути" переиспользует уже существующий
// ATTACK_MOVE_AGGRO_BONUS (07-...js) — тот же радиус, которым вражеский ИИ
// в attack-move замечает турели/юнитов по дороге (ИИ №40) — а не изобретаем
// третье magic-число. Логика полностью симметрична с ИИ.
//
// Подключать ПОСЛЕДНИМ в index.html, после js/27-ai-active-defense-tactics.js.

(function patchUpdateCombatForEnrouteEngagement() {
  if (typeof updateCombat !== "function") return;
  if (typeof findNearestEnemyInRange !== "function") return;
  if (typeof findAttackableAt !== "function") return;

  const _updateCombatOriginal = updateCombat;

  updateCombat = function (dtMs) {
    Object.values(State.units).forEach(u => {
      const def = UnitDefs[u.type];
      if (!def || !def.canAttack) return;

      // Интересует ТОЛЬКО случай "явная цель-здание, без attack-move" —
      // именно он не проходит через автопоиск в оригинальном updateCombat.
      // Юниты в attackMoveMode, юниты без цели, юниты, атакующие другого
      // юнита явно (клик по юниту тоже ставит attackMoveMode=false, но
      // тогда target уже и так юнит — трогать нечего, изначальная цель уже
      // "правильная") этот патч не трогает вообще.
      if (u.attackMoveMode) return;
      if (!u.attackTargetId) return;

      const explicitTarget = findAttackableAt(u.attackTargetId);
      if (!explicitTarget || explicitTarget.hp <= 0) return; // оригинал сам разберётся (цель потеряна/умерла)
      // Цель — уже юнит (не здание): не вмешиваемся, это не наш случай.
      if (State.units[explicitTarget.id]) return;

      // Запоминаем исходную цель-здание один раз — чтобы вернуться к ней,
      // когда рядом не останется вражеских юнитов. Если явная цель сменилась
      // (игрок отдал новый приказ на другое здание) — buildingTargetId
      // тоже обновляем, не залипаем на старую.
      if (u.buildingTargetId !== explicitTarget.id) {
        u.buildingTargetId = explicitTarget.id;
      }

      const aggroRange = def.attackRange + ATTACK_MOVE_AGGRO_BONUS;
      const enemyUnitNearby = findNearestEnemyInRange(u, aggroRange);

      // findNearestEnemyInRange может вернуть и здание (общая функция для
      // юнитов+зданий, см. 07-...js) — интересует ТОЛЬКО живой вражеский
      // ЮНИТ, здания игнорируем здесь (иначе просто вернули бы ту же
      // explicitTarget или другое здание — не то, что нужно чинить).
      const enemyUnit = (enemyUnitNearby && State.units[enemyUnitNearby.id] && enemyUnitNearby.hp > 0)
        ? enemyUnitNearby : null;

      if (enemyUnit) {
        // Переключаемся на вражеского юнита, не теряя buildingTargetId —
        // как только он умрёт/уйдёт из радиуса, следующий тик снова
        // окажется в ветке "explicitTarget — здание" этого же патча и
        // либо найдёт другого enemyUnit рядом, либо (если никого не
        // осталось) просто пропустит патч и отдаст управление оригиналу,
        // который продолжит идти к зданию как раньше.
        if (u.attackTargetId !== enemyUnit.id) {
          u.attackTargetId = enemyUnit.id;
          // На саму цель-здание физически не идём в этом тике — обычный
          // ход updateCombat ниже (оригинал) сам решит: если враг в
          // радиусе атаки — бьёт, если нет — подходит к нему через
          // setUnitDestination, как к любой другой явной цели.
        }
      } else if (u.buildingTargetId != null && u.attackTargetId !== u.buildingTargetId) {
        // Рядом никого нет, но attackTargetId сейчас указывает на
        // вражеского юнита, которого мы только что убили/потеряли из
        // радиуса — возвращаем исходную цель-здание, чтобы юнит
        // продолжил делать то, что ему явно приказал игрок.
        const backTarget = findAttackableAt(u.buildingTargetId);
        if (backTarget && backTarget.hp > 0) {
          u.attackTargetId = u.buildingTargetId;
        } else {
          // Здание уже разрушено кем-то другим (или это была призрачная
          // стена) — нечего возвращать, чистим ссылку.
          u.buildingTargetId = null;
        }
      }
    });

    _updateCombatOriginal(dtMs);
  };
})();
