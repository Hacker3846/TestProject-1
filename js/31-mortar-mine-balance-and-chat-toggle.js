/* ---------------------------- ИИ №48: кнопка "Скрыть чат" ---------------------------- */
// Прямой запрос пользователя (в дополнение к правкам баланса мортиры/мины,
// см. изменения прямо в 25-mortar-and-mines.js — там же, где эти сущности
// определены, а не отдельным патчем поверх): "добавь в меню с 'выделение'
// и 'ии помощник' кнопку скрыть чат тот в котором про постройки и про
// врага верещят".
//
// "Чат" здесь — это #log (05-init-world.js, logMsg()): лента сообщений
// "Строится: ...", "Недостаточно кредитов", "Мина-ловушка сработала",
// атаки/предупреждения врага и т.д. Кнопка размещена в index.html внутри
// #selPanel (панель "ВЫДЕЛЕНИЕ", где уже лежит кнопка "Совет
// ИИ-командующего" — по прямому запросу пользователя разместить рядом с
// этими двумя блоками) — сама разметка кнопки в index.html
// (#toggleChatLogBtn), этот файл только навешивает поведение, тем же
// приёмом "работаем с уже готовым DOM-элементом", что и остальной HUD
// (10-hud.js).
//
// РЕШЕНИЕ: скрываем ЛОГ ЦЕЛИКОМ через CSS (display:none на #log), а не
// останавливаем logMsg() — сообщения продолжают копиться в DOM как обычно
// (в т.ч. пока чат скрыт), просто не отображаются. Так при повторном
// нажатии "Показать чат" пользователь сразу видит накопившуюся историю, а
// не пустую ленту — logMsg() (05-init-world.js) не патчится и не
// дублируется, он ничего не знает о скрытии и продолжает работать как
// раньше.
//
// Состояние не сохраняется между перезагрузками страницы намеренно (нет
// такого явного требования в запросе) — при каждом старте чат виден по
// умолчанию, как и раньше.
(function setupChatLogToggle() {
  const btn = document.getElementById("toggleChatLogBtn");
  const log = document.getElementById("log");
  if (!btn || !log) return; // разметка не найдена — тихо ничего не делаем, остальной HUD не должен из-за этого падать

  let hidden = false;

  function applyState() {
    log.style.display = hidden ? "none" : "";
    btn.textContent = hidden ? "🗨 Показать чат" : "🗨 Скрыть чат";
  }

  btn.addEventListener("click", () => {
    hidden = !hidden;
    applyState();
  });

  applyState();
})();
