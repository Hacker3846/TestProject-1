/* ---------------------------- ИИ №41: "месть турели" ---------------------------- */
// Прямой запрос пользователя: "ИИ должен специально первее разрушать турели,
// которые ранили его юнита или технику, чтобы ИИ специально подводил юнитов
// к таким турелям". Это СИЛЬНЕЕ, чем уже существующий ATTACK_MOVE_AGGRO_BONUS
// (см. 07-game-loop-combat.js, ИИ №40) — тот патч даёт юниту просто заметить
// турель, если она оказалась в увеличенном радиусе обнаружения по пути.
// Здесь же нужна ПАМЯТЬ: турель могла ранить юнита и оказаться уже вне
// радиуса (юнит прошёл мимо, отступил, был отброшен боем) — юнит должен
// целенаправленно СВЕРНУТЬ и пойти мстить именно ей, а не просто отреагировать,
// если она снова окажется рядом.
//
// Реализация — 2 независимых патча, оба "переопределение после объявления"
// (тот же приём проекта, что 13b-21):
//  1) updateDefensiveStructures (07) патчится, чтобы при попадании турели по
//     юниту записывать u.grudgeTurretId = id турели-обидчика на самого юнита.
//  2) updateCombat (07) патчится, чтобы юниты С grudgeTurretId (турель ещё
//     жива) считали её целью С НАИВЫСШИМ приоритетом — выше явного
//     attackTargetId и выше обычного attack-move автопоиска, и физически шли
//     к ней (setUnitDestination), даже если она далеко за пределами
//     ATTACK_MOVE_AGGRO_BONUS/attackRange.
//
// Ограничения (сознательные, чтобы не превратить это в "юнит бросает всё и
// уходит через полкарты навсегда"):
//  - Грудж заводится ТОЛЬКО на турели (BuildingDefs[...].type==="turret"),
//    не на любое здание/юнита — запрос пользователя буквально про турели.
//    Обычная "бей стреляющего" логика (19-...js) уже покрывает юнитов/прочие
//    здания в радиусе, дублировать её на грудж не нужно.
//  - Грудж применяется ТОЛЬКО к юнитам вражеского ИИ (ownerId===enemyPlayerId)
//    — по формулировке запроса это про поведение ИИ-противника, не про
//    юнитов игрока (симметричный грудж для игрока не запрашивался и добавил
//    бы игроку принудительное поведение, которое он не просил и не может
//    выключить).
//  - CHASE_LEASH_RADIUS (поводок attack-move, 07-game-loop-combat.js)
//    сознательно НЕ применяется к grudge-цели — если бы применялся, юнит,
//    получивший урон уже ПОСЛЕ того как отошёл от точки attack-move дальше
//    leash, никогда не смог бы дойти до турели-обидчика, что прямо
//    противоречило бы запросу "специально подводил юнитов к таким турелям".
//    Взамен есть более узкое ограничение — только турели, не любая цель,
//    так что юнит не может уйти "мстить" куда угодно, только к конкретной
//    вражеской турели, которая уже реально стреляла именно по нему.
//  - Грудж НЕ переключается на другую турель, если та стреляет по юниту
//    ВТОРОЙ — юнит держит первую замеченную турель-обидчика, пока она жива.
//    Это то же самое требование "не переключаться между несколькими
//    опасными целями", что уже применено к обычной боевой цели (см. ИИ №40,
//    19-ai-target-priority-and-clustering.js) — только распространено и на
//    грудж, чтобы поведение было последовательным.
//  - Как только турель-обидчик уничтожена — grudgeTurretId сбрасывается,
//    юнит возвращается к обычной логике (attackTargetId/attack-move
//    автопоиск), никакого зависания в "мести никому".
//
// Подключать ПОСЛЕДНИМ в game.html, после 21-ai-base-strategy.js.

(function patchUpdateDefensiveStructuresForGrudge() {
  if (typeof updateDefensiveStructures !== "function") return;
  const _updateDefensiveStructures = updateDefensiveStructures;
  updateDefensiveStructures = function (dtMs) {
    // Снимок "кто ещё жив и сколько у кого hp ДО удара" не нужен — нам
    // достаточно перехватить именно попадания турели по юниту, что проще
    // сделать не оборачиванием чужого цикла (это бы задвоило логику урона),
    // а отдельным ЛЁГКИМ проходом ПОСЛЕ оригинальной функции: сравниваем
    // attackTargetId каждой живой турели ИИ на юнита, у которого только что
    // сработал её attackCooldownLeft (т.е. она стреляла именно в этом тике).
    // Проще и надёжнее: патчим не сам updateDefensiveStructures целиком (это
    // означало бы дублировать всю функцию 1:1, включая будущие правки,
    // которые легко разойдутся), а перехватываем результат — записываем
    // grudge ПОСЛЕ вызова оригинала, читая b.attackTargetId и b.attackCooldownLeft,
    // которые оригинал уже выставил. Кулдаун турели сброшен на полный
    // attackCooldown РОВНО в тот тик, когда она ударила — этим и определяем
    // "только что выстрелила", не дублируя проверку урона.
    _updateDefensiveStructures(dtMs);

    Object.values(State.buildings).forEach(b => {
      if (b.hp <= 0) return;
      const def = BuildingDefs[b.type];
      if (!def || !def.canAttack) return;
      if (b.type !== "turret") return; // грудж только на турели, см. комментарий выше
      if (!b.attackTargetId) return;
      // "только что выстрелила" — её кулдаун ровно полный (updateDefensiveStructures
      // выставляет b.attackCooldownLeft = def.attackCooldown ИМЕННО в тик удара).
      if (b.attackCooldownLeft !== def.attackCooldown) return;

      const victim = State.units[b.attackTargetId];
      if (!victim || victim.hp <= 0) return;
      if (victim.ownerId !== enemyPlayerId) return; // грудж только для юнитов вражеского ИИ, см. комментарий выше
      if (victim.grudgeTurretId != null) return; // уже мстит кому-то — не переключаем (см. комментарий выше)

      victim.grudgeTurretId = b.id;
    });
  };
})();

(function patchUpdateCombatForGrudge() {
  if (typeof updateCombat !== "function") return;
  const _updateCombat = updateCombat;
  updateCombat = function (dtMs) {
    // Грудж-цель имеет приоритет НАД обычным выбором цели этого тика — но
    // сама механика урона/движения/кулдауна для боя как такового не
    // дублируется здесь: мы просто, ДО вызова оригинала, принудительно
    // выставляем u.attackTargetId на турель-обидчика тем юнитам, у кого есть
    // живой grudgeTurretId, и не даём его "затереть" внутри оригинала —
    // оригинал (07) уважает уже выставленный attackTargetId (см. её код:
    // "1) Явная цель... — приоритет"), так что достаточно проставить его
    // здесь раньше, никакого дублирования боевого цикла не требуется.
    Object.values(State.units).forEach(u => {
      if (u.hp <= 0) return;
      if (u.ownerId !== enemyPlayerId) return;
      if (u.grudgeTurretId == null) return;

      const turret = State.buildings[u.grudgeTurretId];
      if (!turret || turret.hp <= 0) {
        // турель-обидчик уже уничтожена (или это сделал кто-то другой) —
        // грудж закрыт, юнит возвращается к обычному поведению без
        // дополнительных действий с нашей стороны.
        u.grudgeTurretId = null;
        return;
      }

      // Грудж-цель приоритетнее любой другой явной цели, которую юнит мог
      // получить в этом же тике (например, автопоиск уже нашёл кого-то
      // ближе) — принудительно переключаем на турель-обидчика. Если юнит
      // уже и так атакует именно эту турель — переприсвоение ничего не
      // меняет, просто идемпотентно.
      u.attackTargetId = turret.id;

      // Грудж НЕ подчиняется CHASE_LEASH_RADIUS (см. комментарий-обоснование
      // в шапке файла) — принудительно держим attackMoveMode включённым (сам
      // бой/сближение отработает updateCombat как обычно), но НЕ трогаем
      // attackMoveHomeX/Y здесь: если оригинал уже прервал бы юнита leash'ем
      // на обычной цели, для grudge-турели это не должно случиться — проще
      // всего временно "выключить" условие поводка для этого тика, обнулив
      // attackMoveHomeX/Y ТОЛЬКО когда есть активный грудж (леш у обычного
      // 07-кода срабатывает только если attackMoveHomeX != null).
      if (u.attackMoveMode) {
        u.attackMoveHomeX = null;
        u.attackMoveHomeY = null;
      }
    });

    _updateCombat(dtMs);

    // После боя: если грудж-турель за это время умерла (юнит её добил в
    // этом же тике — killBuilding уже удалила её из State.buildings), явно
    // чистим поле, чтобы не таскать мёртвый id дальше без необходимости.
    Object.values(State.units).forEach(u => {
      if (u.ownerId !== enemyPlayerId) return;
      if (u.grudgeTurretId != null && !State.buildings[u.grudgeTurretId]) {
        u.grudgeTurretId = null;
      }
    });
  };
})();
