const REFINERY_PRICE_STEP = 25;

// Единая точка расчёта АКТУАЛЬНОЙ цены здания с учётом роста (пока растёт
// только refinery, см. выше). Используется во всех местах 10-hud.js, где
// раньше читали def.cost напрямую для зданий (buildBuildBar — цена на
// кнопке, tryStartBuilding — проверка при входе в режим размещения,
// confirmBuildPlacement — проверка и списание при подтверждении) — один
// источник истины вместо трёх копий формулы.
function getBuildingCost(key, player) {
  const def = BuildingDefs[key];
  if (!def) return 0;
  if (key === "refinery" && player) {
    return def.cost + (player.refineryBuiltCount || 0) * REFINERY_PRICE_STEP;
  }
  return def.cost;
}
